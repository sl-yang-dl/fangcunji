// 从 {年份}.js 中提取记录
function loadRecords(year) {
  const file = join(ROOT, "src", "data", `${year}.js`);
  if (!existsSync(file)) return [];
  const code = readFileSync(file, "utf-8");
  // 用正则提取 JSON 数组（const YEAR_xxx = [...];）
  const m = code.match(/const YEAR_\d+ = (\[[\s\S]*?\]);\s*\nexport/);
  if (!m) return [];
  try {
    return JSON.parse(m[1]);
  } catch (e) {
    console.error(`✗ 解析 ${year}.js 失败：${e.message}`);
    return [];
  }
}

// 归一化引号/空白，避免弯引号导致匹配失败
function norm(s) {
  return String(s)
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/\s+/g, " ")
    .trim();
}

// 匹配套票名：先用精确 themeEn，再尝试 name 关键词
// setMap 的 key 也做归一化缓存，确保弯引号/空白一致
const _normCache = new Map();
function normMap(setMap) {
  let m = _normCache.get(setMap);
  if (!m) {
    m = new Map();
    for (const k of Object.keys(setMap)) m.set(norm(k), setMap[k]);
    _normCache.set(setMap, m);
  }
  return m;
}

function resolveName(rec, setMap) {
  const themeEn = norm(rec.themeEn || "");
  const name = norm(rec.name || "");
  const nm = normMap(setMap);
  if (themeEn && nm.has(themeEn)) return nm.get(themeEn);
  // name 关键词兜底
  for (const [key, val] of nm) {
    if (name.includes(key)) return val;
  }
  return "";
}

